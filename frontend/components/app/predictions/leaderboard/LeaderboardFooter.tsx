import { ChevronUp } from 'lucide-react';

interface LeaderboardFooterProps {
  hasMore?: boolean;
  isLoadingMore?: boolean;
  onLoadMore?: () => void;
  loadMoreDisabled?: boolean;
}

export default function LeaderboardFooter({
  hasMore = false,
  isLoadingMore = false,
  onLoadMore,
  loadMoreDisabled = false,
}: LeaderboardFooterProps) {
  return (
    <div className="space-y-0 border-t border-white/10 bg-white/[0.02]">
      {hasMore && onLoadMore ? (
        <div className="flex justify-center px-3 py-3">
          <button
            type="button"
            onClick={onLoadMore}
            disabled={loadMoreDisabled || isLoadingMore}
            className="rounded-lg border border-white/15 bg-white/5 px-4 py-2 text-sm font-medium text-white transition-colors hover:bg-white/10 disabled:cursor-not-allowed disabled:opacity-50"
          >
            {isLoadingMore ? 'Loading…' : 'Load more'}
          </button>
        </div>
      ) : null}
      <div className="flex items-center gap-1 px-3 py-2.5 text-xs text-gray-500">
        <ChevronUp className="h-3.5 w-3.5" aria-hidden />
        Rankings are generated by our proprietary scoring model.
      </div>
    </div>
  );
}
